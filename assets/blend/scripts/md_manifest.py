"""Regenerate assets/export/MANIFEST.md from assets/registry.json (Claude B uploads only).

Run with any Python (Blender's included):  exec(open(r"<repo>/assets/blend/scripts/md_manifest.py").read(), {"__file__": ...})
"""

import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
CLEAN_FROM = "PRP_Tree"  # first upload exported with bake_space_transform
UPGRADE_PROPS = {"PRP_Dolly", "PRP_LoadingRamp"}
ROOM_DRESSING = {"PRP_KitchenCounter", "PRP_Bathtub", "PRP_Toilet", "PRP_BedFrame", "PRP_Rug", "PRP_BathroomSink", "PRP_Fireplace"}


def target(n):
    if n.startswith("REF_"):
        return "(test only, deleted)", "Box", "4x1x2 scale check"
    if n.endswith("_Frac"):
        return "Assets.Fractured", "Box", "4-6 chunks, client-only debris"
    if n.startswith("FUR_"):
        return "Assets.Furniture", "Hull", ""
    if n.startswith("TRK_") and "_Body" in n:
        note = "rig parts stay as collision" + ("; paint variant, same rig placement" if not n.endswith("_Body") else "")
        return "Assets.Trucks", "Hull (CanCollide=false, visual only)", note
    if n.startswith("TRK_"):
        return "Assets.Trucks", "Hull", ""
    if n in UPGRADE_PROPS:
        return "Assets.Props", "Hull", "upgrade prop"
    if n == "PRP_Strap":
        return "Assets.Props", "Box", "upgrade prop; long band is a Beam"
    if n.startswith("COS_"):
        return "Assets.Props", "Box", "hat; add Handle/HatAttachment"
    if n in ROOM_DRESSING:
        return "RoomTemplates (replaces placeholder part)", "Box", "decoration: anchored, CanCollide/CanTouch/CanQuery off"
    return "Assets.Props", "Box", "decoration: anchored, CanCollide/CanTouch/CanQuery off"


def main():
    with open(os.path.join(ROOT, "assets", "registry.json"), encoding="utf-8") as f:
        reg = [a for a in json.load(f) if a.get("uploadedBy") == "ClaudeB"]
    order = [a["name"] for a in reg]
    clean = set(order[order.index(CLEAN_FROM):]) if CLEAN_FROM in order else set()
    lines = [
        "# Export manifest (Claude B)",
        "",
        "Generated by `assets/blend/scripts/md_manifest.py` from `assets/registry.json`.",
        "",
        "One FBX per asset. Units: 1 Blender unit = 1 stud (scene unit scale 0.01, FBX written in cm).",
        "Front faces Blender -Y (Roblox -Z), origin at bottom centre, transforms applied, one shared palette",
        "material (`assets/blend/palette.png`, uploaded as PAL_Palette 76201554143630; set MeshPart.TextureID).",
        "Grip points and collision proxies are added in Studio.",
        "",
        "**PivotOffset:** assets marked `-90X` were exported before `bake_space_transform` and carry a -90 deg X",
        "rotation in MeshPart.PivotOffset; fix on insert with `part.PivotOffset = CFrame.new(part.PivotOffset.Position)`.",
        "",
        "| File | Asset ID | Studio target | Collision fidelity | Pivot | Notes |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for a in reg:
        t, c, note = target(a["name"])
        pivot = "clean" if a["name"] in clean else "-90X"
        lines.append(f"| {os.path.basename(a['file'])} | {a['assetId']} | {t} | {c} | {pivot} | {note} |")
    with open(os.path.join(ROOT, "assets", "export", "MANIFEST.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return len(reg)


if __name__ == "__main__" or "__file__" in globals():
    print(main(), "rows")
